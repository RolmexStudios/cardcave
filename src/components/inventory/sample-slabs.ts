export function sampleSlabInventory(
  variant: Extract<
    BrochureInventoryVariant,
    "case" | "binder" | "vault" | "cards"
  >,
): BrochureInventoryContent {
  const copy = COPY[variant];
  return {
    variant,
    eyebrow: copy.eyebrow,
    title: copy.title,
    intro: copy.intro,
    teaserLimit: 12,
    viewAllLabel: "",
    showStatusFilter: true,
    showPrices: false,
    sectionSize: "auto",
    vehicles: [],
    items: SLABS.map((item) =>
      slabSchema.parse({
        yearEnd: "",
        showPrice: true,
        ...item,
      }),
    ),
    groupBy: variant === "case" ? "band" : "",
  };
}
